con = sqlite3.connect(DB)
cur = con.cursor()
n_upd = n_ins = 0
for key, (ru, kz) in TEXTS.items():
    if cur.execute("SELECT 1 FROM SiteText WHERE key=?", (key,)).fetchone():
        cur.execute(
            "UPDATE SiteText SET valueRu=?, valueKz=?, updatedAt=datetime('now') WHERE key=?",
            (ru, kz, key),
        )
        n_upd += 1
    else:
        cur.execute(
            "INSERT INTO SiteText (key, valueRu, valueKz, updatedAt) VALUES (?,?,?, datetime('now'))",
            (key, ru, kz),
        )
        n_ins += 1
con.commit()
total = con.execute("SELECT COUNT(*) FROM SiteText").fetchone()[0]
con.close()
print(f"SiteText: обновлено {n_upd}, добавлено {n_ins}, всего в БД {total}")
