def service_direction_and_kz(name: str):
    """→ (slug|None, kz|None). None = консультация/неизвестно (логировать)."""
    if name in SERVICES:
        d, kz = SERVICES[name]
        return d, kz
    if name in UZI_KZ:
        return "uzi", UZI_KZ[name]
    if name.endswith(" детям"):
        base = name[: -len(" детям")].strip()
        if base in SERVICES:
            d, kz = SERVICES[base]
            return d, f"{kz} (балаларға)"
        if base in UZI_KZ:
            return "uzi", f"{UZI_KZ[base]} (балаларға)"
    return None, None
